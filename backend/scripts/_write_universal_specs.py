"""Пишет JSON-спеки прототипов в backend/universal/specs/.

Запуск из корня проекта:
  python -m backend.scripts._write_universal_specs

Математика (OGE/EGE/база) строится из bank_data с template_text/answer.
"""

from __future__ import annotations

import json
from pathlib import Path

from backend.bank_data import ege_base_math, ege_profile_math, oge_math
from backend.universal.bank_bridge import prototypes_from_bank_tasks

SPECS_DIR = Path(__file__).resolve().parent.parent / "universal" / "specs"


def _proto(n: int, part: int, title: str, instruction: str) -> dict:
    return {
        "task_number": n,
        "part": part,
        "prototype_title": title,
        "prompt_instruction": instruction,
    }


def _dump(name: str, payload: dict) -> None:
    SPECS_DIR.mkdir(parents=True, exist_ok=True)
    path = SPECS_DIR / name
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with_tpl = sum(1 for p in payload["prototypes"] if p.get("template_text"))
    print(f"wrote {path} ({len(payload['prototypes'])} prototypes, {with_tpl} with templates)")


