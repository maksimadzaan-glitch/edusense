def main() -> None:
    raw = json.loads(PACK.read_text(encoding="utf-8"))
    by_id = {v["variant_id"]: v for v in raw["variants"]}

    by_id["oge_rus_var_03"]["tasks"] = VAR_03_TASKS
    by_id["oge_rus_var_04"]["tasks"] = VAR_04_TASKS
    by_id["oge_rus_var_05"]["tasks"] = VAR_05_TASKS

    # var_02: полное эссе 13.1/13.2/13.3
    tasks2 = by_id["oge_rus_var_02"]["tasks"]
    for i, t in enumerate(tasks2):
        if int(t["task_number"]) == 12:
            tasks2[i] = essay(
                theme="Что такое настоящая дружба?",
                quote="Когда Мишка вернулся в школу, мы поняли, что настоящая дружба делает людей сильнее.",
                linguistic="Зачем в тексте нужны средства связи предложений?",
            )
            break

    raw["pack_info"]["total_variants"] = len(raw["variants"])
    raw["pack_info"]["total_tasks"] = sum(
        1 + len(v.get("tasks") or []) for v in raw["variants"]
    )  # izlo + tasks (изложение отдельно в izlozhenie)

    PACK.write_text(
        json.dumps(raw, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    for v in raw["variants"]:
        nums = sorted(int(t["task_number"]) for t in v["tasks"])
        print(v["variant_id"], nums, "ok" if nums == list(range(2, 13)) else "GAP")


if __name__ == "__main__":
    main()
